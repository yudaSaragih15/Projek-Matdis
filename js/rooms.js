function labelRuang(r) {
    if (r.c && r.n) return r.c + ' \u2014 ' + r.n;
    if (r.c) return 'Ruang ' + r.c;
    return r.n;
}

// Jarak dari pintu masuk gedung (lantai 1) ke ruangan
function jarakDalamGedung(r) {
    if (!r) return 0;
    return JARAK_DALAM.dasar + (r.f - 1) * JARAK_DALAM.perLantai;
}

// Jarak antar dua ruangan di gedung yang sama
function jarakAntarRuang(a, b) {
    if (a.f === b.f) return JARAK_DALAM.dasar;
    return JARAK_DALAM.dasar + Math.abs(a.f - b.f) * JARAK_DALAM.perLantai;
}
